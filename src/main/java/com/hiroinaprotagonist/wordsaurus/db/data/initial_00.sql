CREATE TABLE clouds
(
    cloud_id    uuid                     default gen_random_uuid(),
    name        varchar(255)                                                  not null UNIQUE,
    explicit    boolean,
    inserted_at timestamp with time zone default timezone('utc'::text, now()) not null,
    updated_at  timestamp with time zone default timezone('utc'::text, now()) not null,
    PRIMARY KEY (cloud_id)
);

CREATE TABLE words
(
    word_id     int generated by default as identity primary key,
    name        varchar(255)                                                  not null UNIQUE,
    explicit    boolean                                                       not null,
    inserted_at timestamp with time zone default timezone('utc'::text, now()) not null,
    updated_at  timestamp with time zone default timezone('utc'::text, now()) not null,
    mw_meta_id varchar,
    mw_meta_uuid varchar,
    mw_tuuid varchar,
    mw_tsrc varchar,
    mw_meta_src varchar,
    mw_meta_section varchar,
    mw_hw varchar,
    stems varchar[],
    synonyms varchar[][],
    antonyms varchar[][]
);

CREATE TABLE clouds_words
(
    cloud_id    uuid not null REFERENCES clouds ON DELETE CASCADE,
    word_id     int  not null REFERENCES words ON DELETE CASCADE,
    inserted_at timestamp with time zone default timezone('utc'::text, now()) not null,
    updated_at  timestamp with time zone default timezone('utc'::text, now()) not null,
    UNIQUE (cloud_id, word_id),
    PRIMARY KEY (cloud_id, word_id)
);